const assert = require('node:assert/strict');
const path = require('node:path');

module.exports = async ({page, root, act, calls, note, chooseTab, noOverflow, avatarId, setPostMode, setProfileMode, setAvatarMode}) => {
  const last = method => calls.filter(call => call.method === method).at(-1)?.args;
  const count = method => calls.filter(call => call.method === method).length;
  const back = () => page.evaluate(() => window.AppBack());
  const idle = () => page.waitForFunction(() => !document.querySelector('[data-motion-scene],.motion-outgoing'));
  const cards = n => page.waitForFunction(n => document.querySelectorAll('#book-list .bookcard').length === n, n);
  const dialogClosed = () => page.waitForSelector('#modal-root [role=dialog]', {state:'detached'});
  await cards(24);
  await act('categories').click();
  await page.getByRole('button', {name:'新测试题材', exact:true}).waitFor();
  assert.deepEqual(await page.locator('#category-options button').allTextContents(), ['全部题材','节操','新测试题材']);
  await act('refreshCategories').click();
  await page.getByRole('button', {name:'刷新后的题材', exact:true}).waitFor();
  assert.deepEqual(await page.locator('#category-options button').allTextContents(), ['全部题材','节操','刷新后的题材']);
  await page.locator('#category-search').fill('节操');
  assert.equal(await page.locator('#category-options button').count(), 1);
  await page.getByRole('button', {name:'节操', exact:true}).click();
  await page.getByRole('button', {name:/题材与作者测试作品/}).waitFor();
  assert.equal(last('list').theme, 'jiecao');
  note('topic picker uses the current source catalogue, removes obsolete topics on refresh and filters by identifier');

  await act('book').first().click();
  await page.waitForSelector('[data-act="openTag"][data-id="jiecao"]');
  await idle();
  assert.equal(await act('openTag').count(), 8);
  await page.locator('#chapter-filter').fill('第02');
  await act('openAuthor').first().evaluate(button => button.click());
  await cards(24);
  assert.equal(last('list').author, 'fixture-author');
  assert.equal(await page.locator('.catalog-heading h1').innerText(), '有标识的作者');
  await act('moreList').click();
  await cards(26);
  assert.equal(last('list').offset, 24);
  const scroll = await page.evaluate(() => { scrollTo(0, 500); return scrollY; });
  await act('book').nth(4).evaluate(button => button.click());
  await page.waitForSelector('.detail-shell');
  await back();
  await cards(26);
  assert.ok(Math.abs(await page.evaluate(() => scrollY) - scroll) < 3);
  await back();
  await page.waitForSelector('#chapter-filter');
  assert.equal(await page.locator('#chapter-filter').inputValue(), '第02');
  note('all detail tags render, and author pagination and nested back navigation retain list and detail state');

  await act('openAuthor').nth(1).click();
  await cards(1);
  assert.equal(last('search').type, 'author');
  assert.equal(last('search').q, '仅名称的作者');
  await back();
  await page.locator('[data-act="openTag"][data-id="jiecao"]').click();
  await cards(24);
  assert.equal(last('list').theme, 'jiecao');
  assert.equal(await page.locator('.catalog-heading h1').innerText(), '节操');
  await back();
  await act('openComicComments').click();
  const reply = page.locator('[data-act="replyComment"][data-id="1000"]');
  await reply.click();
  assert.equal(count('postComment'), 0);
  await page.locator('#login-username').fill('fixture-reader');
  await page.locator('#login-password').fill('fixture-Password+/&=密码');
  await page.locator('#login-submit').click();
  await page.getByRole('dialog', {name:'回复评论'}).waitFor();
  assert.match(await page.locator('.reply-quote strong').innerText(), /<svg onload=/);
  assert.equal(await page.locator('.reply-quote svg,.reply-quote img').count(), 0);
  assert.equal(count('postComment'), 0);
  await page.locator('#comment-text').fill('第一位读者的回复 & 🙂');
  await act('closeModal').click();
  await page.locator('[data-act="replyComment"][data-id="1001"]').click();
  assert.equal(await page.locator('#comment-text').inputValue(), '');
  await act('closeModal').click();
  await reply.click();
  assert.equal(await page.locator('#comment-text').inputValue(), '第一位读者的回复 & 🙂');
  setPostMode('denied');
  await page.locator('#comment-submit').click();
  await page.getByText('请先在原版验证邮箱', {exact:true}).waitFor();
  assert.equal(await page.locator('#comment-text').inputValue(), '第一位读者的回复 & 🙂');
  assert.equal(last('postComment').replyId, '1000');
  setPostMode('ok');
  await page.locator('#comment-submit').click();
  await page.locator('#replies-1000').getByText('第一位读者的回复 & 🙂', {exact:true}).waitFor();
  assert.equal(last('comments').replyId, '1000');
  await page.locator('#replies-1000 [data-act="replyComment"]').click();
  await page.locator('#comment-text').fill('回复串里的继续回复');
  await page.locator('#comment-submit').click();
  await page.locator('#replies-1000').getByText('回复串里的继续回复', {exact:true}).waitFor();
  assert.equal(last('postComment').replyId, '90000');
  assert.equal(last('comments').replyId, '1000');
  note('comic replies preserve their target across login, separate drafts, keep rejected input and refresh the correct thread');

  await back();
  await back();
  await chooseTab('settings');
  await page.waitForFunction(() => document.querySelector('#settings-account .account-avatar img')?.naturalWidth > 0);
  await act('editProfile').click();
  await page.locator('#profile-nickname').fill('新昵称 & 中文 🙂');
  await act('chooseAvatar').click();
  await page.waitForFunction(() => document.querySelector('#profile-photo-preview img')?.src.includes('/avatar-preview?'));
  setAvatarMode('cancel');
  await act('chooseAvatar').click();
  await page.locator('#profile-choose:not([disabled])').waitFor();
  assert.match(await page.locator('#profile-photo-preview img').getAttribute('src'), /avatar-preview/);
  setProfileMode('denied');
  await page.locator('#profile-save').click();
  await page.getByText('源站暂时限制资料修改', {exact:true}).waitFor();
  assert.equal(await page.locator('#profile-nickname').inputValue(), '新昵称 & 中文 🙂');
  assert.deepEqual(last('saveProfile'), {nickname:'新昵称 & 中文 🙂',avatarId});
  setProfileMode('ok');
  await page.locator('#profile-save').click();
  await dialogClosed();
  await page.locator('#settings-account .account-info').getByText('新昵称 & 中文 🙂', {exact:true}).waitFor();
  assert.equal(await page.locator('#settings-account .account-info p').innerText(), 'fixture-reader');
  assert.match(await page.locator('#settings-account .account-avatar img').getAttribute('src'), /account-new-avatar/);
  assert.equal(await page.evaluate(() => window.fixtureDiscardedAvatar), avatarId);
  note('account editing previews a picked photo, preserves a cancelled pick and saves nickname and avatar through the account bridge');

  await act('editProfile').click();
  await page.locator('#profile-nickname').fill('保存状态检查');
  setProfileMode('unconfirmed');
  await page.locator('#profile-save').click();
  await page.locator('#profile-check').waitFor();
  assert.equal(await page.locator('#profile-save').isDisabled(), true);
  const saves = count('saveProfile');
  await act('checkProfile').click();
  await dialogClosed();
  assert.equal(count('saveProfile'), saves);
  await page.setViewportSize({width:320,height:740});
  await noOverflow();
  await page.screenshot({path:path.join(root,'checks/settings-profile-1.13.png')});
  await act('editProfile').click();
  await noOverflow();
  await page.screenshot({path:path.join(root,'checks/edit-profile-1.13.png')});
  note('uncertain profile saves can be checked without repeating the write, and the editor fits a narrow phone');
};
